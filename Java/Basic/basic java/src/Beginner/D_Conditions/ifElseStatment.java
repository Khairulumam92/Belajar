package Beginner.D_Conditions;

public class ifElseStatment {
    public static void main(String[] args) {
        int nilaiPertama = 5, nilaiKedua = 10;

        if (nilaiPertama > nilaiKedua) {
            System.out.println("Nilai " + nilaiPertama + " lebih besar dari nilai " + nilaiKedua);
        } else {
            System.out.println("Nilai pertama lebih kecil dari nilai kedua");
        }
        System.out.println("Selesai");
    }
}
