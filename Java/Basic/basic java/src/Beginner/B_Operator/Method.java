package Beginner.B_Operator;

public class Method {
    int a = 10;
    int b = 5;

    void penjumlahan() {
        int hasil = a + b;
        System.out.println("Hasil penjumlahan: " + hasil);
    }

    void pengurangan() {
        int hasil = a - b;
        System.out.println("Hasil pengurangan: " + hasil);
    }

    void perkalian() {
        int hasil = a * b;
        System.out.println("Hasil perkalian: " + hasil);
    }

    void pembagian() {
        int hasil = a / b;
        System.out.println("Hasil pembagian: " + hasil);
    }
}
